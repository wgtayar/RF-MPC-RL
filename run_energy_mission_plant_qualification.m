function report = run_energy_mission_plant_qualification(outputRoot, options)
%RUN_ENERGY_MISSION_PLANT_QUALIFICATION Native full mission on the locked plant.
% Runs the energy-mission plant (tracked swing, locked 18650 pack) for the
% full mission at one fixed requested governor speed with drive limits
% ENFORCED, captures the drive trace, and screens the same trace on candidate
% series counts at the declared start SOCs (interval-level offline replay).
% No learning; no exploration noise; no pack change.
if nargin < 2, options = struct(); end
defaults = struct('initial_soc', .95, 'screen_series_counts', 6:8, ...
    'screen_initial_soc', [.25 .95 1], 'requested_speed_m_s', .58, ...
    'command_mode', 'governor', 'hold_s', []);
assert(all(ismember(fieldnames(options), fieldnames(defaults))), ...
    'plantQualification:Options', 'Unknown option.');
for f = fieldnames(defaults).'
    if ~isfield(options, f{1}), options.(f{1}) = defaults.(f{1}); end
end
validateattributes(options.requested_speed_m_s, {'double'}, {'scalar','real','finite','positive'});
assert(ismember(options.command_mode, {'governor','direct'}), 'plantQualification:CommandMode', ...
    'command_mode must be governor (RL action path) or direct (plant characterization).');
assert(isempty(options.hold_s) || (isscalar(options.hold_s) && options.hold_s > 0), ...
    'plantQualification:Hold', 'hold_s must be empty (full mission) or a positive duration.');
src = bootstrap_RF_MPC_RL(); sha = gitValue(src, 'rev-parse HEAD');
assert(isempty(gitValue(src, 'status --porcelain')), 'plantQualification:Dirty', ...
    'Commit source before qualification.');
assert(~isfolder(outputRoot) && ~isfile(outputRoot), 'plantQualification:Exists', ...
    'Use a new output directory.');
b = setup_energy_mission_rl(struct('initial_soc', options.initial_soc)); c = b.cfg;
mkdir(outputRoot); save(fullfile(outputRoot, 'configuration.mat'), 'b', '-v7.3');
meta = struct('schema', 'energy_mission_plant_qualification_v1', 'source_sha', sha, ...
    'source_branch', gitValue(src, 'branch --show-current'), 'source_dirty', false, ...
    'matlab', version, 'timestamp_utc', ...
    char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'options', options, 'seed', c.RNG_SEED, 'reward_version', c.REWARD.version, ...
    'swing_model', swing_model_of(c), 'pack_specification', c.BATTERY.fixed_pack_spec, ...
    'training', false, 'learning_rates_used', [], 'exploration_noise_used', [], ...
    'enforce_drive_limits', true, ...
    'configuration_sha256', sha256_file(fullfile(outputRoot, 'configuration.mat')));
writeJson(outputRoot, 'manifest', meta);
gammaV = (options.requested_speed_m_s - c.V_MIN)/(c.V_MAX - c.V_MIN);
assert(gammaV >= c.GAMMA_V_MIN && gammaV <= c.GAMMA_V_MAX + 1e-12, 'plantQualification:Speed', ...
    'Requested speed is outside the governor action bounds.');
gammaV = min(gammaV, c.GAMMA_V_MAX);
s = initialize_mpc_replay_state(c, 0); origin = s.Xt(1); target = origin + c.MISSION.D_TARGET_M;
duration = c.MISSION_DURATION; stopAt = target;
if ~isempty(options.hold_s), duration = options.hold_s; stopAt = []; end
attitude = struct('steps',0,'max_tilt',0,'tilt_sq',0,'max_rate',0,'exceed',0,'excess_sq',0);
directControl = [];
if strcmp(options.command_mode, 'direct')
    % Plant characterization: command the speed directly at the start, MPC
    % reference acceleration from the largest configured acceleration action.
    directControl = resolve_replay_action([zeros(3,1); c.GAMMA_V_MISSION; c.GAMMA_A_MAX], ...
        s, c, b.lower_abs, b.upper_abs);
    directControl.v_cmd = options.requested_speed_m_s;
    directControl.reference_mode = configured_reference_mode(c);
end
drive = zeros(round(duration/.01), 53); n = 0; solves = 0; failed = 0;
terminal = 'time_limit'; started = tic;
try
    while s.t < duration - 1e-8
        if ~isempty(directControl)
            control = directControl;
        elseif mod(round(s.t*100), round(c.CHUNK_DURATION*c.APPLY_EVERY*100)) == 0
            control = resolve_replay_action([zeros(3,1); gammaV; c.GAMMA_A_MIN], ...
                s, c, b.lower_abs, b.upper_abs);
            control.reference_mode = configured_reference_mode(c);
        end
        o = struct('duration_s', min(c.CHUNK_DURATION, duration - s.t), ...
            'capture_trace', false, 'capture_drive_trace', true, 'update_proxy', false, ...
            'update_battery', true, 'enforce_drive_limits', true, ...
            'stop_at_position_x_m', stopAt, ...
            'solver_strategy', 'default_one_shot_fallback_tight_primal_v1');
        [s, out] = simulate_mpc_horizon(s, control, c, o);
        count = size(out.drive_trace, 1); drive(n+(1:count), :) = out.drive_trace; n = n + count;
        solves = solves + out.qp_solve_count; failed = failed + out.qp_failed_count;
        a = out.attitude; attitude.steps = attitude.steps + a.integrated_steps;
        attitude.max_tilt = max(attitude.max_tilt, a.max_tilt_rad); attitude.tilt_sq = attitude.tilt_sq + a.tilt_square_sum;
        attitude.max_rate = max(attitude.max_rate, a.max_body_rate_rad_s); attitude.exceed = attitude.exceed + a.tilt_exceedance_steps;
        attitude.excess_sq = attitude.excess_sq + a.tilt_excess_square_sum;
        fprintf('[plant] t=%.2f x=%.3f SOC=%.6f terminal=%s\n', s.t, s.Xt(1)-origin, ...
            s.energy.soc, out.terminal_reason);
        if out.terminal_reason ~= "horizon_complete"
            terminal = char(out.terminal_reason); break
        end
    end
    drive = drive(1:n, :); columns = out.drive_trace_columns;
    save(fullfile(outputRoot, 'drive_trace.mat'), 'drive', 'columns', '-v7.3');
    ratio = repmat(c.ENERGY.ratio(:), 4, 1).';
    screen = replay_drive_trace_on_pack(drive, options.screen_series_counts, ...
        options.screen_initial_soc, c.BATTERY.C_nom_Ah, c.BATTERY.terminal_margin);
    writetable(screen, fullfile(outputRoot, 'series_screen.csv'));
    report = struct('source_sha', sha, 'terminal', terminal, ...
        'mission_complete', strcmp(terminal, 'mission_target_reached'), 'hold_s', options.hold_s, ...
        'duration_s', s.t, 'distance_m', s.Xt(1) - origin, 'wall_s', toc(started), ...
        'qp_solves', solves, 'qp_failed', failed, 'initial_soc', options.initial_soc, ...
        'final_true_soc', s.energy.soc, 'final_estimated_soc', s.energy.estimate(1), ...
        'charge_As', s.energy.chargeAs, 'energy_Wh', s.energy.energyWh, ...
        'mean_pack_current_A', s.energy.chargeAs/max(s.t, eps), ...
        'voltage_limit_intervals', s.energy.voltageLimitSteps, ...
        'torque_limit_intervals', s.energy.torqueLimitSteps, ...
        'peak_required_V', max(drive(:,4)), 'p99_required_V', prctile(drive(:,4), 99), ...
        'peak_motor_torque_Nm', max(drive(:,5)), ...
        'peak_joint_speed_rad_s', max(abs(drive(:,18:29)), [], 'all'), ...
        'peak_motor_speed_rad_s', max(abs(drive(:,18:29)).*ratio, [], 'all'), ...
        'mean_drive_W', mean(drive(:,3)), 'drive_J_per_m', s.energy.energyWh*3600/max(s.Xt(1)-origin, eps), ...
        'command_mode', options.command_mode, 'commanded_a_m_s2', localA(directControl), ...
        'max_tilt_rad', attitude.max_tilt, 'rms_tilt_rad', sqrt(attitude.tilt_sq/max(attitude.steps,1)), ...
        'max_body_rate_rad_s', attitude.max_rate, 'tilt_exceedance_fraction', attitude.exceed/max(attitude.steps,1), ...
        'rms_tilt_excess_rad', sqrt(attitude.excess_sq/max(attitude.steps,1)), ...
        'tilt_threshold_rad', c.STABILITY.tilt_threshold_rad, 'drive_trace_sha256', ...
        sha256_file(fullfile(outputRoot, 'drive_trace.mat')), ...
        'series_screen', screen, 'achieved_motion_claim', true, ...
        'scope', 'One fixed requested-speed policy; not an RL action distribution, hardware or real-time qualification.');
    assert(strcmp(sha, gitValue(src, 'rev-parse HEAD')) && ...
        isempty(gitValue(src, 'status --porcelain')), ...
        'plantQualification:SourceChanged', 'Source changed during qualification.');
    writeJson(outputRoot, 'result', report);
catch exception
    save(fullfile(outputRoot, 'interrupted_state.mat'), 's', 'n', '-v7.3');
    writeJson(outputRoot, 'failure', struct('identifier', exception.identifier, ...
        'message', exception.message, 'source_sha', sha));
    rethrow(exception)
end
end
function value = gitValue(src, args)
[status, value] = system(sprintf('git -C "%s" %s', src, args)); assert(status == 0);
value = strtrim(value);
end
function writeJson(root, name, value)
f = fopen(fullfile(root, [name '.json']), 'w'); assert(f >= 0);
closeFile = onCleanup(@()fclose(f)); fprintf(f, '%s\n', jsonencode(value, 'PrettyPrint', true));
end
function a = localA(control)
a = NaN; if ~isempty(control), a = control.a_cmd; end
end
