function checkpoint=load_energy_mission_checkpoint(input)
%LOAD_ENERGY_MISSION_CHECKPOINT Verify completed, captured initial/final TD3 weights.
input=char(input);
if isfolder(input),path=fullfile(input,'training','final_agent.mat');else,path=input;end
assert(isfile(path),'energyPolicy:Checkpoint','A captured initial/final checkpoint is required.');
[~,a]=fileattrib(path);path=a.Name;[trainingFolder,name,ext]=fileparts(path);[root,folder]=fileparts(trainingFolder);
assert(strcmp(folder,'training') && strcmp(ext,'.mat') && ismember(name,{'initial_agent','final_agent'}), ...
 'energyPolicy:Checkpoint','Use a completed capture training/initial_agent.mat or training/final_agent.mat.');
indexPath=fullfile(trainingFolder,'artifact_sha256.csv');
assert(isfile(indexPath),'energyPolicy:ArtifactIndex','Completed artifact index is required.');
index=readtable(indexPath,'TextType','string');
required={['training/' name ext],'manifest/configuration.mat','manifest/run.mat', ...
 'manifest/completion.mat','training/report.json','training/agent_specification.json'};
hashes=struct();
for k=1:numel(required)
 row=find(replace(index.file,'\','/')==string(required{k}));
 assert(isscalar(row),'energyPolicy:ArtifactIndex','Each required artifact needs exactly one checksum.');
 p=fullfile(root,required{k});
 assert(isfile(p) && strcmp(sha256_file(p),index.sha256(row)), ...
  'energyPolicy:Checksum','Captured checkpoint/configuration/provenance bytes differ from their index.');
 hashes.(matlab.lang.makeValidName(required{k}))=char(index.sha256(row));
end
s=load(fullfile(root,'manifest','configuration.mat'),'cfg');cfg=s.cfg;
s=load(fullfile(root,'manifest','run.mat'),'manifest');manifest=s.manifest;
s=load(fullfile(root,'manifest','completion.mat'),'completion');completion=s.completion;
report=jsondecode(fileread(fullfile(trainingFolder,'report.json')));
spec=jsondecode(fileread(fullfile(trainingFolder,'agent_specification.json')));
assert(~isfile(fullfile(trainingFolder,'failure.json')) && ...
 ismember(completion.status,{'train_complete','build_only_complete'}) && strcmp(completion.status,report.outcome) && ...
 ~manifest.source_dirty && ~report.source_dirty && report.source_unchanged && ...
 isequaln(report.source_start,report.source_finish) && ~report.source_start.dirty && isempty(report.source_start.status) && ...
 strcmp(report.source_start.sha,manifest.source_sha) && strcmp(report.source_start.branch,manifest.source_branch) && ...
 strcmp(report.source_sha,manifest.source_sha), ...
 'energyPolicy:SourceProvenance','Require completed, clean, unchanged training provenance.');
assert(strcmp(manifest.configuration_sha256,sha256_file(fullfile(root,'manifest','configuration.mat'))) && ...
 strcmp(report.configuration_sha256,manifest.configuration_sha256), ...
 'energyPolicy:ConfigurationHash','Training configuration provenance differs.');
assert(isfield(cfg,'ENERGY_RL') && strcmp(cfg.ENERGY_RL.version,'energy_mission_v1') && ...
 ismember(cfg.REWARD.version,{'reward_energy_mission_v1','reward_energy_mission_v2','reward_energy_mission_v3'}) && strcmp(cfg.PHASE3.observation_schema,'observation_energy_mission_v1') && ...
 strcmp(cfg.PHASE3.reward_version,cfg.REWARD.version) && ...
 strcmp(manifest.observation_schema_version,cfg.PHASE3.observation_schema) && strcmp(manifest.reward_version,cfg.PHASE3.reward_version), ...
 'energyPolicy:Schema','Require the paired energy-mission observation/reward schemas.');
assert(strcmp(cfg.BATTERY.fixed_pack_spec.id,cfg.ENERGY_RL.reference.pack_id), ...
 'energyPolicy:Pack','Charge-reference evidence must belong to the captured fixed pack.');
saved=load(path,'agent','agentSpec');
assert(all(isfield(saved,{'agent','agentSpec'})) && isa(saved.agent,'rl.agent.rlTD3Agent'), ...
 'energyPolicy:Agent','Checkpoint must contain a captured TD3 agent and specification.');
assert(isequaln(jsondecode(jsonencode(saved.agentSpec)),spec),'energyPolicy:AgentSpec','Agent specification differs from capture.');
schema=energy_mission_observation_schema(cfg);obs=getObservationInfo(saved.agent);act=getActionInfo(saved.agent);actor=getActor(saved.agent);
assert(numel(obs)==1 && isequal(obs.Dimension,[schema.dimension,1]) && numel(act)==1 && isequal(act.Dimension,[5,1]) && ...
 all(act.LowerLimit(:)==-1) && all(act.UpperLimit(:)==1) && isa(actor,'rl.function.rlContinuousDeterministicActor') && ...
 spec.observation_dimension==schema.dimension && strcmp(spec.observation_schema,schema.version) && ...
 strcmp(spec.action_schema,'energy_mission_normalized_action_v1'), ...
 'energyPolicy:Interface','Actor dimensions and normalized actions must match the active energy schema.');
[~,map]=energy_mission_action_transform(zeros(5,1),cfg);
assert(isequal(spec.action_physical_scale(:),map.scale) && isequal(spec.action_physical_bias(:),map.bias) && ...
 spec.sample_time_seconds==cfg.CHUNK_DURATION*cfg.APPLY_EVERY && saved.agent.AgentOptions.SampleTime==spec.sample_time_seconds && ...
 saved.agent.AgentOptions.DiscountFactor==1,'energyPolicy:ActionMapping','Action scales, decision time or discount differ.');
bundle=struct('cfg',cfg,'initial_R',cfg.PHASE3.initial_R,'lower_abs',cfg.PHASE3.lower_R,'upper_abs',cfg.PHASE3.upper_R);
episodes=report.episodes_trained;stage='final';if strcmp(name,'initial_agent'),episodes=0;stage='initial';end
checkpoint=struct('root',root,'path',path,'sha256',sha256_file(path),'stage',stage, ...
 'checkpoint_episodes_trained',episodes,'source_run_episodes_trained',report.episodes_trained, ...
 'training_source_sha',manifest.source_sha,'configuration_sha256',manifest.configuration_sha256, ...
 'manifest',manifest,'agent_specification',spec,'bundle',bundle,'actor',actor,'verified_artifact_hashes',hashes);
end
