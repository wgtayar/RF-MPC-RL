function settings = energy_mission_agent_options(overrides)
%energy_mission_agent_options Explicit, provisional TD3 test settings.
% These settings are reproducible starting points, not tuned performance.
    if nargin < 1, overrides=struct(); end
    settings = struct('algorithm','TD3','version','energy_mission_td3_v1', ...
        'hyperparameter_status','provisional_not_performance_tuned', ...
        'hidden_units',128,'actor_learn_rate',3e-4,'critic_learn_rate',3e-4, ...
        'gradient_threshold',1,'discount_factor',1,'target_smooth_factor',0.005, ...
        'policy_update_frequency',2,'target_update_frequency',2, ...
        'mini_batch_size',64,'num_warm_start_steps',64, ...
        'experience_buffer_length',100000,'learning_frequency',1, ...
        'max_minibatch_per_epoch',1,'num_epoch',1, ...
        'exploration_standard_deviation',0.10, ...
        'target_standard_deviation',0.20,'target_noise_clip',0.50);
    assert(isstruct(overrides) && isscalar(overrides), ...
        'energy_mission_agent_options:Options','Options must be a scalar struct.');
    locked = {'algorithm','version','hyperparameter_status','discount_factor'};
    names = fieldnames(overrides);
    assert(all(ismember(names,setdiff(fieldnames(settings),locked))), ...
        'energy_mission_agent_options:UnknownOption', ...
        'Unknown or locked option; the finite-horizon objective requires discount_factor=1.');
    for k=1:numel(names), settings.(names{k})=overrides.(names{k}); end
    integers = {'hidden_units','policy_update_frequency','target_update_frequency', ...
        'mini_batch_size','num_warm_start_steps','experience_buffer_length', ...
        'learning_frequency','max_minibatch_per_epoch','num_epoch'};
    for k=1:numel(integers)
        validateattributes(settings.(integers{k}),{'numeric'}, ...
            {'scalar','real','finite','positive','integer'},mfilename,integers{k});
    end
    positives = {'actor_learn_rate','critic_learn_rate','gradient_threshold', ...
        'target_smooth_factor','target_noise_clip'};
    for k=1:numel(positives)
        validateattributes(settings.(positives{k}),{'numeric'}, ...
            {'scalar','real','finite','positive'},mfilename,positives{k});
    end
    noises = {'exploration_standard_deviation','target_standard_deviation'};
    for k=1:numel(noises)
        validateattributes(settings.(noises{k}),{'numeric'}, ...
            {'scalar','real','finite','nonnegative'},mfilename,noises{k});
    end
    assert(settings.target_smooth_factor<=1 && ...
        settings.num_warm_start_steps>=settings.mini_batch_size && ...
        settings.experience_buffer_length>=settings.num_warm_start_steps, ...
        'energy_mission_agent_options:Inconsistent','Invalid target smoothing, warmstart or replay capacity.');
end
