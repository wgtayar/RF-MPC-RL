function report=run_energy_mission_qualification(root)
%RUN_ENERGY_MISSION_QUALIFICATION Reproducible math and native learning checks.
src=bootstrap_RF_MPC_RL();sha=gitValue(src,'rev-parse HEAD');
assert(isempty(gitValue(src,'status --porcelain')),'energyQualification:Dirty','Commit before qualification.');
assert(~isfolder(root) && ~isfile(root),'energyQualification:Exists','Use a new directory.');
mkdir(root);b=setup_energy_mission_rl();save(fullfile(root,'configuration.mat'),'b');
meta=struct('schema','energy_mission_qualification_v1','source_sha',sha,'source_dirty',false, ...
 'source_branch',gitValue(src,'branch --show-current'), ...
 'timestamp_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
 'configuration_sha256',sha256_file(fullfile(root,'configuration.mat')), ...
 'seed',b.cfg.RNG_SEED,'reward_version',b.cfg.REWARD.version, ...
 'observation_version',b.cfg.ENERGY_RL.observation_schema,'pack_id',b.cfg.BATTERY.fixed_pack_spec.id, ...
 'training_scope','Two native MPC transitions with explicit smoke-only optimizer settings; no performance tuning.');
writeJson(root,'manifest',meta);
try
 names={'testFixedPackEnergy','testFixedPackMath','testFixedPackFailureHandling', ...
  'testFixedPackTargetCrossing','testBatteryManuscriptConfig','testPhase3BatteryFeedback', ...
  'testMpcReplayTimeGrid','testReferencePositionContinuity','testPhase3TargetStop', ...
  'testPhase3TerminalSemantics','testFixedPackPolicyEvaluation','testFixedPackLegacyTiming', ...
  'testInstantaneousDrive','testPackSizingAnalysis','testSizingDemandTrace', ...
  'testPackSizingBound','testResolvedEnergy','testFrozenPack', ...
  'testEnergyMissionObjective','testEnergyMissionTraining','testPackDemandReplay','testEnergyMissionDataset', ...
  'testTrackedSwing','testAttitudeTelemetry','testEnergyMissionPolicyEvaluation','testEnergyMissionTiming'};
 files=cellfun(@(n)fullfile(src,'tests',[n '.m']),names,'UniformOutput',false);
 r=runtests(files);writetable(table(string({r.Name})',[r.Passed]',[r.Failed]',[r.Incomplete]', ...
  'VariableNames',{'name','passed','failed','incomplete'}),fullfile(root,'tests.csv'));assertSuccess(r);
 build=train_energy_mission_rl(fullfile(root,'agent_build'),struct());
 setup=struct('target_distance_m',.02*(320/600),'mission_duration_s',.02,'decision_interval_s',.01);
 opt=struct('mode','train','setup_options',setup,'max_episodes',1, ...
  'agent_options',struct('mini_batch_size',1,'num_warm_start_steps',1, ...
  'policy_update_frequency',1,'target_update_frequency',1));
 smoke=train_energy_mission_rl(fullfile(root,'learning_smoke'),opt);
 assert(smoke.training_decisions==2 && smoke.actor_parameters_changed && all(smoke.critic_parameters_changed), ...
  'energyQualification:Learning','Smoke must execute both transitions and update actor and both critics.');
 assert(strcmp(sha,gitValue(src,'rev-parse HEAD')) && isempty(gitValue(src,'status --porcelain')), ...
  'energyQualification:SourceChanged','Source changed during qualification.');
 report=struct('schema',meta.schema,'source_sha',sha,'source_dirty',false, ...
  'tests_passed',nnz([r.Passed]),'tests_failed',nnz([r.Failed]),'tests_incomplete',nnz([r.Incomplete]), ...
  'build',build,'learning_smoke',smoke,'performance_tuned',false,'training_promoted',false, ...
  'scope','Software accounting, captured native interface, fresh TD3 and actual optimizer update checks only.');
 writeJson(root,'result',report);
catch e
 writeJson(root,'failure',struct('source_sha',sha,'identifier',e.identifier,'message',e.message,'stack',{e.stack}));rethrow(e)
end
end
function v=gitValue(root,args)
[s,v]=system(sprintf('git -C "%s" %s',root,args));assert(s==0);v=strtrim(v);
end
function writeJson(root,name,v)
f=fopen(fullfile(root,[name '.json']),'w');assert(f>=0);c=onCleanup(@()fclose(f));fprintf(f,'%s\n',jsonencode(v,'PrettyPrint',true));
end
