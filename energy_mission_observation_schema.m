function schema = energy_mission_observation_schema(cfg)
%ENERGY_MISSION_OBSERVATION_SCHEMA Executed dynamics and available battery state.
    unit = energy_mission_scales(cfg);
    base = phase3_observation_v2_schema(cfg,'observation_v2_dynamic_health_candidate_v2');
    names = base.names;
    names(names=="battery_margin") = "estimated_soc";
    names(names=="previous_Ieq") = "previous_pack_current_1C";
    extra = ["consumed_charge_reference","projected_remaining_charge_reference", ...
        "projected_reserve_surplus_reference","has_charge_forecast", ...
        "pack_voltage_per_series_cell","drive_headroom_per_series_cell", ...
        "estimated_rc1_V","estimated_rc2_V","estimated_rc3_V", ...
        "has_voltage_measurement","has_drive_headroom"]';
    schema = struct('version','observation_energy_mission_v1', ...
        'base_schema',base.version,'base_dimension',base.dimension, ...
        'names',[names;extra],'dimension',base.dimension+numel(extra), ...
        'scales',[base.scales;ones(numel(extra),1)], ...
        'identity_transform',[base.identity_transform; ...
            false;false;false;true;false;false;false;false;false;true;true], ...
        'electrical_units',unit,'training_promoted',false, ...
        'continuous_transform','asinh(raw/scale); electrical charge values are expressed in frozen-reference units.', ...
        'forecast_scope','Historical cumulative Coulombs per net forward meter times remaining distance; no terrain/stationarity guarantee or safety-bound claim.', ...
        'missing_rule','Unavailable raw values stay NaN in audit, encode as zero with context flags.');
end
